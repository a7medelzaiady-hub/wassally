String _normalize(String raw) => raw
    .toLowerCase()
    .replaceAll(RegExp(r'[ً-ٰٟـ]'), '')
    .replaceAll(RegExp('[أإآ]'), 'ا')
    .replaceAll('ة', 'ه')
    .replaceAll('ى', 'ي')
    .replaceAll(RegExp(r'\s+'), ' ')
    .trim();

/// بيرجّع اقتراح للاسم ده، أو null لو الاسم مش في القاموس.
ProductSuggestion? suggestProduct(String rawName) {
  final name = rawName.trim();
  if (name.length < 2) return null;
  final n = ' ${_normalize(name)} ';
  for (final r in _rules) {
    for (final w in r.words) {
      // كلمة كاملة بس (أو بـ«ال»): «بن» ما تطابقش «بنادول»، و«خل» ما تطابقش «خلطة».
      final key = _normalize(w);
      if (n.contains(' $key ') || n.contains(' ال$key ')) {
        return ProductSuggestion(
          section: r.section,
          unit: r.unit,
          // قالب «{name}» لوحده كان هيكرر الاسم؛ نضيف الوحدة عشان الوصف يفيد العميل.
          description: r.template == '{name}'
              ? '$name • بال${r.unit}'
              : r.template.replaceAll('{name}', name),
          optionGroups: r.options,
        );
      }
    }
  }
  return null;
}
