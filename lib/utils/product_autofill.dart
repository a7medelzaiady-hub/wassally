/// اقتراح تفاصيل الصنف من اسمه بس، من قاموس ثابت جوه التطبيق.
///
/// صاحب المحل يكتب «طماطم» والسعر، والتطبيق يقترح وصف قصير فيه الوحدة،
/// وخيارات جاهزة للمشروبات والسندوتشات. مفيش أي قراءة من Firestore ولا نت ولا AI،
/// ومفيش حاجة بتتحفظ غير لما صاحب المحل يدوس «استخدم الاقتراح».
class ProductSuggestion {
  /// القسم (للعرض في الاقتراح بس، مش بيتحفظ).
  final String section;

  /// الوحدة اللي بيتباع بيها الصنف غالبًا (كيلو، علبة، رغيف...).
  final String unit;

  /// وصف قصير جاهز (فيه الوحدة).
  final String description;

  /// خيارات مقترحة (سكر، إضافات...). فاضية لأغلب الأصناف.
  final List<OptionGroup> optionGroups;

  const ProductSuggestion({
    required this.section,
    required this.unit,
    required this.description,
    this.optionGroups = const [],
  });
}

class _Rule {
  final List<String> words;
  final String section;
  final String unit;

  /// قالب الوصف؛ {name} = اسم الصنف زي ما صاحب المحل كتبه.
  final String template;
  final List<OptionGroup> options;
  const _Rule(this.words, this.section, this.unit, this.template,
      [this.options = const []]);
}

