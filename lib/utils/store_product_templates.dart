/// توحيد الاختلافات البسيطة في كتابة الأسماء لكشف التكرار محليًا.
String normalizeProductKey(String raw) => raw
    .toLowerCase()
    .replaceAll(RegExp(r'[\u064B-\u065F\u0670\u0640]'), '')
    .replaceAll('أ', 'ا')
    .replaceAll('إ', 'ا')
    .replaceAll('آ', 'ا')
    .replaceAll('ة', 'ه')
    .replaceAll('ى', 'ي')
    .replaceAll(RegExp(r'[\s\-–—_]+'), ' ')
    .trim()
    .split(' ')
    .map((word) => word.startsWith('ال') && word.length > 4
        ? word.substring(2)
        : word)
    .join(' ');

/// تعديل الأسعار على الأصناف المحددة فقط. الأسعار المطبّق عليها خصم
/// تبقى خارج التعديل كي لا نكسر السعر القديم/الجديد في العرض.
double adjustedProductPrice(double oldPrice, double percent) =>
    ((oldPrice * (1 + percent / 100)) * 100).round() / 100;
